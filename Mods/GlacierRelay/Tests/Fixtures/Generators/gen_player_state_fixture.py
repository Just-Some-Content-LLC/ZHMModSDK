"""Generate Tests/Fixtures/B0PlayerState.h from the B0 native log.

Usage:
    python3 gen_player_state_fixture.py <native log> <out header>

Input:  the B0 probe's native log (evidence corpus `%TEMP%\\glacier-m0\\hitmen\\b0-run1\\relay-20261007-014849-93996.log`,
        2026-10-07, Paris, game 3.280.0.0). Read only; never modified or regenerated by this script.
Output: the C++ header holding every Trespassing and HoldingIllegalWeapon event the engine's JSON writer logged (two and
        four in B0), exactly as logged, plus role indices and the one weapon definition/instance id pair. To verify a
        committed header, generate into a temporary path and compare byte for byte.

Identifier-removal rules (the only edits to the logged text): the `"UserId":"..."` and `"SessionId":"..."` members
(the user's account id and the platform session id) are removed textually with their leading comma; every other byte of
each event, including ContractSessionId, ContractId, Origin, Timestamp and the event Id, is kept verbatim. The script
asserts that the Value object is unchanged by the removal.
"""
import json, re, sys

log, out = sys.argv[1], sys.argv[2]
NAMES = ("Trespassing", "HoldingIllegalWeapon")
rows = []
for line in open(log, encoding="utf-8", errors="replace"):
    m = re.search(r"sent #(\d+) \(index (\d+), frame (\d+)\): (\{.*\})\s*$", line)
    if not m:
        continue
    text = m.group(4)
    e = json.loads(text)
    if e.get("Name") not in NAMES:
        continue
    stripped = re.sub(r',"UserId":"[^"]*"', "", text)
    stripped = re.sub(r',"SessionId":"[^"]*"', "", stripped)
    assert json.loads(stripped)["Value"] == e["Value"]
    rows.append((int(m.group(1)), int(m.group(2)), int(m.group(3)), e["Name"], e["Value"], stripped))

assert len(rows) == 6, len(rows)
counts = {n: sum(1 for r in rows if r[3] == n) for n in NAMES}
assert counts == {"Trespassing": 2, "HoldingIllegalWeapon": 4}, counts
weapons = [r[4]["WeaponEquipped"] for r in rows if r[3] == "HoldingIllegalWeapon" and "WeaponEquipped" in r[4]]
assert len(weapons) == 2 and weapons[0] == weapons[1], weapons
assert all("WeaponEquipped" not in r[4] for r in rows if r[3] == "HoldingIllegalWeapon" and not r[4]["IsHoldingIllegalWeapon"])

names = {
    0: ("k_TrespassingEntered", "IsTrespassing true, RoomId 6"),
    1: ("k_TrespassingLeft", "IsTrespassing false, RoomId 3; 25 ms after the first Disguise"),
    2: ("k_IllegalWeaponDrawn1", "IsHoldingIllegalWeapon true, WeaponEquipped (the loadout pistol)"),
    3: ("k_IllegalWeaponHolstered1", "IsHoldingIllegalWeapon false, no WeaponEquipped"),
    4: ("k_IllegalWeaponDrawn2", "IsHoldingIllegalWeapon true, WeaponEquipped (the loadout pistol)"),
    5: ("k_IllegalWeaponHolstered2", "IsHoldingIllegalWeapon false, no WeaponEquipped"),
}

with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("#pragma once\n\n")
    f.write("// The 2 Trespassing and 4 HoldingIllegalWeapon events the game emitted in the B0 probe (2026-10-07, Paris, game\n")
    f.write("// 3.280.0.0), verbatim from the native log except that the user and platform session identifiers are removed.\n")
    f.write("// Trespassing: {IsTrespassing: bool, RoomId: number} (one true, one false). HoldingIllegalWeapon: {IsHoldingIllegalWeapon:\n")
    f.write("// true, WeaponEquipped: {IsPerceivedAsWeapon, InstanceId (non-empty), ItemType, ItemName, RepositoryId, OnlineTraits,\n")
    f.write("// Category, ActionRewardType}} on the two true forms; {IsHoldingIllegalWeapon: false} with no WeaponEquipped on the two\n")
    f.write("// false forms (glacier-relay M2 design, section 46.1). The engine field types are unknown: the JSON writer's text is\n")
    f.write("// the only evidence. Generated from the B0 corpus; do not edit by hand.\n\n")
    f.write("#include <cstddef>\n\nnamespace B0Fixtures\n{\n")
    f.write("    struct RawPlayerStateEvent { int probe_sequence; int event_index; int frame; const char* json; };\n\n")
    f.write("    inline const RawPlayerStateEvent k_PlayerState[] = {\n")
    for seq, idx, frame, name, value, text in rows:
        f.write(f'        {{{seq}, {idx}, {frame}, R"json({text})json"}},\n')
    f.write("    };\n\n")
    f.write("    inline constexpr size_t k_PlayerStateCount = sizeof(k_PlayerState) / sizeof(k_PlayerState[0]);\n\n")
    f.write("    // Indices into k_PlayerState, by role in the B0 session (order of emission).\n")
    for i, (seq, idx, frame, name, value, text) in enumerate(rows):
        f.write(f"    inline constexpr size_t {names[i][0]:<26} = {i}; // {name} index {idx}, Timestamp {json.loads(text)['Timestamp']}: {names[i][1]}\n")
    w = weapons[0]
    f.write("\n    // The one weapon the two true forms named: a definition id and, unlike every B0 world item, a non-empty instance id.\n")
    f.write(f'    inline constexpr const char* k_IllegalWeaponDefinition = "{w["RepositoryId"]}"; // {w["ItemName"]}\n')
    f.write(f'    inline constexpr const char* k_IllegalWeaponInstance = "{w["InstanceId"]}";\n')
    f.write("}\n")
print("wrote", out, "rows", len(rows))
for r in rows:
    print(r[0], r[1], r[3], r[4], json.loads(r[5])["Timestamp"])
